// check-default-expand.cjs — v0.18.3 §2.1 default first expand smoke.
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const ok = (m) => console.log('  ✓', m);
  const fail = (m) => { console.error('FAIL:', m); process.exitCode = 1; throw new Error(m); };
  await p.goto('http://127.0.0.1:7340/');
  await p.waitForLoadState('networkidle');
  await p.evaluate(() => localStorage.removeItem('vcm-sidebar-expanded'));
  await p.reload();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(200);
  const allProjects = await p.$$eval('[data-c="sidebar-project-row"]', els => els.map(e => e.getAttribute('data-project')));
  console.log('order:', allProjects);
  if (allProjects.length < 2) fail('need ≥ 2 projects');
  const [first, second] = allProjects;
  const subnavVisible = (name) => p.$eval(`[data-project="${name}"][data-c="sidebar-project-row"] [data-c="sidebar-subnav"]`, el => getComputedStyle(el).display !== 'none');
  if (!(await subnavVisible(first))) fail(`first ${first} should be auto-expanded`);
  ok(`first (${first}) expanded`);
  if (await subnavVisible(second)) fail(`second ${second} should be collapsed`);
  ok(`second (${second}) collapsed`);
  await p.click(`[data-project="${second}"][data-c="sidebar-project-row"] [data-c="sidebar-project-toggle"]`);
  await p.waitForTimeout(100);
  if (await subnavVisible(first)) fail('first should collapse (accordion)');
  ok('first collapsed');
  if (!(await subnavVisible(second))) fail('second should expand');
  ok('second expanded');
  const stored = await p.evaluate(() => JSON.parse(localStorage.getItem('vcm-sidebar-expanded') || '[]'));
  if (!stored.includes(second)) fail(`ls should include ${second}`);
  if (stored.includes(first)) fail(`ls should NOT include ${first}`);
  ok(`ls = ${JSON.stringify(stored)}`);
  await p.goto(`http://127.0.0.1:7340/projects/${first}`);
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(200);
  if (!(await subnavVisible(first))) fail(`${first} should be expanded on its page`);
  ok(`${first} expanded`);
  if (await subnavVisible(second)) fail(`${second} should collapse on /projects/${first}`);
  ok(`${second} collapsed (accordion)`);
  await p.goto('http://127.0.0.1:7340/');
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(200);
  if (await subnavVisible(first)) fail(`first should NOT expand when ${second} preview exists`);
  if (!(await subnavVisible(second))) fail(`manual preview ${second} should restore`);
  ok(`preview (${second}) wins`);
  await p.evaluate(() => localStorage.removeItem('vcm-sidebar-expanded'));
  await p.reload();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(200);
  if (!(await subnavVisible(first))) fail(`${first} should be default`);
  if (await subnavVisible(second)) fail(`${second} should be collapsed`);
  ok(`cleared → first (${first}) default`);
  await p.goto(`http://127.0.0.1:7340/projects/${second}/drift`);
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(200);
  if (!(await subnavVisible(second))) fail(`${second} should expand`);
  if (await subnavVisible(first)) fail(`${first} should collapse`);
  ok(`project page correctly expands ${second}`);
  console.log('\n✅ all checks passed');
  await b.close();
})().catch(e => { console.error('\n❌ ERR:', e.message); process.exit(1); });
