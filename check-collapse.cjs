// check-collapse.cjs — v0.18.3 sidebar collapse (ADR-0034 §9) smoke test.
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
  const ok = (m) => console.log('  ✓', m);
  const fail = (m) => { console.error('FAIL:', m); process.exitCode = 1; throw new Error(m); };
  await p.goto('http://127.0.0.1:7340/');
  await p.waitForLoadState('networkidle');
  await p.evaluate(() => localStorage.removeItem('vcm-sidebar-collapsed'));
  await p.reload();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(300);
  const sidebar = p.locator('[data-c="sidebar"]');
  const button = p.locator('[data-c="sidebar-collapse-btn"]');
  const brandText = p.locator('.sidebar-brand-text');
  const navLinkText = p.locator('[data-link="cockpit"] .sidebar-link-text');
  const projName = p.locator('[data-project="vcm-smoke"][data-c="sidebar-project"] .sidebar-project-name');
  const projIcon = p.locator('[data-project="vcm-smoke"][data-c="sidebar-project"] .sidebar-project-icon');
  const subnav = p.locator('[data-project="vcm-smoke"][data-c="sidebar-project-row"] [data-c="sidebar-subnav"]');
  const grid = p.locator('[data-c="shell-grid"]');
  const w0 = await sidebar.evaluate(el => el.getBoundingClientRect().width);
  if (Math.abs(w0 - 240) > 2) fail(`expected 240px, got ${w0}`);
  ok(`sidebar 240px (${w0})`);
  if (!(await brandText.isVisible())) fail('brand text visible');
  ok('brand text visible');
  if (!(await navLinkText.isVisible())) fail('nav link text visible');
  ok('nav link text visible');
  if (!(await projName.isVisible())) fail('project name visible');
  ok('project name visible');
  const iconBg = await projIcon.evaluate(el => getComputedStyle(el).backgroundColor);
  if (iconBg === 'rgba(0, 0, 0, 0)') fail('icon should have hash-color bg');
  ok(`icon hash-color (${iconBg})`);
  if ((await sidebar.getAttribute('data-collapsed')) === 'true') fail('data-collapsed should be false');
  ok('data-collapsed = false');
  const g0 = await grid.evaluate(el => getComputedStyle(el).gridTemplateColumns);
  if (!g0.startsWith('240')) fail(`grid should be 240px, got ${g0}`);
  ok(`grid 240px (${g0})`);
  await button.click();
  await p.waitForTimeout(150);
  const w1 = await sidebar.evaluate(el => el.getBoundingClientRect().width);
  if (Math.abs(w1 - 64) > 2) fail(`expected 64px, got ${w1}`);
  ok(`sidebar 64px (${w1})`);
  if (!(await brandText.isHidden())) fail('brand text hide');
  ok('brand text hidden');
  if (!(await navLinkText.isHidden())) fail('nav link text hide');
  ok('nav link text hidden (no wrap)');
  if (!(await projName.isHidden())) fail('project name hide');
  ok('project name hidden');
  const isz = await projIcon.evaluate(el => Math.round(el.getBoundingClientRect().width));
  if (isz < 20) fail(`icon scale ~24px, got ${isz}`);
  ok(`icon scaled to ${isz}px`);
  if (!(await subnav.evaluate(el => getComputedStyle(el).display === 'none'))) fail('subnav hide');
  ok('subnav hidden (§9.4)');
  if ((await sidebar.getAttribute('data-collapsed')) !== 'true') fail('data-collapsed should be true');
  ok('data-collapsed = true');
  const g1 = await grid.evaluate(el => getComputedStyle(el).gridTemplateColumns);
  if (!g1.startsWith('64')) fail(`grid should be 64px, got ${g1}`);
  ok(`grid 64px (${g1})`);
  if ((await p.evaluate(() => localStorage.getItem('vcm-sidebar-collapsed'))) !== '1') fail('ls should be "1"');
  ok('localStorage = "1"');
  await p.reload();
  await p.waitForLoadState('networkidle');
  await p.waitForTimeout(300);
  const wR = await sidebar.evaluate(el => el.getBoundingClientRect().width);
  if (Math.abs(wR - 64) > 2) fail(`reload expected 64px, got ${wR}`);
  ok(`reload keeps 64px (${wR})`);
  await button.click();
  await p.waitForTimeout(150);
  const wF = await sidebar.evaluate(el => el.getBoundingClientRect().width);
  if (Math.abs(wF - 240) > 2) fail(`expected 240px, got ${wF}`);
  ok(`back to 240px (${wF})`);
  if ((await p.evaluate(() => localStorage.getItem('vcm-sidebar-collapsed'))) !== '0') fail('ls should be "0"');
  ok('localStorage = "0"');
  console.log('\n✅ all checks passed');
  await b.close();
})().catch(e => { console.error('\n❌ ERR:', e.message); process.exit(1); });
